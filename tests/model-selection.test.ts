test('API enforces discovered models, keeps unconfigured QQ usable, and leaves unrelated saves local',async t=>{
 const seen:Array<{method:string;url:string;auth:string}>=[];
 const upstream=http.createServer((req,res)=>{seen.push({method:req.method!,url:req.url!,auth:req.headers.authorization||''});res.setHeader('Content-Type','application/json');res.end(JSON.stringify({data:[{id:'real-model'},{id:'real-aux'}]}))});
 await new Promise<void>(r=>upstream.listen(0,'127.0.0.1',r));permitModelFixture(upstream);t.after(()=>new Promise<void>(r=>upstream.close(()=>r())));
 const root=await mkdtemp(path.resolve('.local/model-selection-'));
 const {app,db,agent}=await createApp({root,agent:false});t.after(()=>app.close());
 const reg=await app.inject({method:'POST',url:'/v1/auth/register',payload:{inviteCode:await issueTestInvite(db,3),email:'models@selection.test',password:'selection-test-password',name:'selection'}});
 assert.equal(reg.statusCode,200);const cookies={fish_session:reg.cookies[0].value};
 const baseUrl=`http://127.0.0.1:${(upstream.address()as any).port}/v1`,config={...defaultConfig,baseUrl};
 const create=(cfg:any)=>app.inject({method:'POST',url:'/v1/bots',cookies,payload:{name:'selection',apiKey:'synthetic-selection-key',config:cfg}});
 const draft=await create(config);assert.equal(draft.statusCode,201,draft.body);assert.equal(seen.length,0);
 const [draftBot]=await db.query('SELECT * FROM bots WHERE id=$1',[draft.json().id]);
 const ctx=await agent.context(draftBot);assert.equal(ctx.apiKey,'','saved key cannot enable SDK fallback without a selected model');
 await agent.ai.provision({...ctx,apiKey:'synthetic-selection-key'});
 const runtime=JSON.parse(await readFile(path.join(ctx.root,'ai/data/cmd_config.json'),'utf8'));
 assert.deepEqual(runtime.provider,[]);assert.equal(runtime.provider_settings.enable,false);assert.equal(runtime.agent_runner.config.model.provider_id,'');
 assert.equal((await create({...config,model:'deepseek-chat'})).statusCode,400);
 const selected={...config,model:'real-model',auxiliaryModel:'real-aux'};
 const made=await create(selected);assert.equal(made.statusCode,201,made.body);const id=made.json().id;
 const save=(cfg:any,revision=1,apiKey?:string)=>app.inject({method:'PUT',url:`/v1/bots/${id}/config`,cookies,payload:{name:'selection',expectedRevision:revision,config:cfg,apiKey}});
 const before=seen.length;
 assert.equal((await save({...selected,systemPrompt:'Edited persona'})).statusCode,200);
 assert.equal(seen.length,before,'persona edit does not refetch models');
 const bad=await save({...selected,model:'imagined'},2);assert.equal(bad.statusCode,400);
 const [same]=await db.query('SELECT revision FROM bots WHERE id=$1',[id]);assert.equal(same.revision,2);
 const staleBefore=seen.length;assert.equal((await save({...selected,model:'real-aux'},1)).statusCode,409);assert.equal(seen.length,staleBefore);
 const changed=await save({...selected,model:'real-aux'},2);assert.equal(changed.statusCode,200,changed.body);
 assert.equal((await save({...selected,baseUrl:baseUrl+'/other'},3)).statusCode,400,'stored key never follows an edited destination');
 assert.ok(seen.every(r=>r.method==='GET'&&r.url==='/v1/models'),'validation never performs paid inference');
});
