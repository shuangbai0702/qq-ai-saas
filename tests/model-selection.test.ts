 await assert.rejects(()=>validateModelSelection({...defaultConfig,model:'deepseek-chat'},'key',undefined,transport),/不在.*列表/);
 await assert.rejects(()=>validateModelSelection({...defaultConfig,model:'real-model'},'',undefined,transport),/API Key/);
