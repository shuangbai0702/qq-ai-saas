import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import os from 'node:os';import path from 'node:path';
import {createApp} from '../apps/control-api/src/app.js';
import {issueTestInvite} from './helpers/invitations.js';
import {reserveCredits,dispatchCredits,receiptCredits,rejectedCredits,recoverCreditReceipts,creditBalance,settleCredits,releaseUndispatchedCredits} from '../apps/control-api/src/platform-credits.js';

test('durable credit receipts recover exactly once; legacy and dispatched unknowns remain reserved',async t=>{
 const {app,db}=await createApp({root:await mkdtemp(path.join(os.tmpdir(),'fish-credit-recovery-')),databaseUrl:'',agent:false});t.after(()=>app.close());
 const auth=await app.inject({method:'POST',url:'/v1/auth/register',payload:{inviteCode:await issueTestInvite(db),name:'fixture',email:'credit-recovery@test.invalid',password:'fixture-password'}});
 assert.equal(auth.statusCode,200,auth.body);const cookies={fish_session:auth.cookies[0].value};
 const made=await app.inject({method:'POST',url:'/v1/bots',cookies,payload:{name:'credit fixture',protocol:'mock'}});assert.equal(made.statusCode,201,made.body);
 const bot=made.json().id,[row]=await db.query('SELECT tenant_id FROM bots WHERE id=$1',[bot]);const tenant=row.tenant_id;
 await db.query('INSERT INTO platform_model_credits(tenant_id,granted) VALUES($1,10000)',[tenant]);
 const hold=()=>db.transaction(tx=>reserveCredits(tx,tenant,bot,100));
 const receipt=await hold(),unknown=await hold(),legacy=await hold(),waiting=await hold();
 await dispatchCredits(db,receipt,'provider-a');await receiptCredits(db,receipt,31);
 await assert.rejects(receiptCredits(db,receipt,32),/credit_receipt_conflict/);
 await assert.rejects(settleCredits(db,receipt,32),/credit_receipt_conflict/);
 await dispatchCredits(db,unknown,'provider-b');
 await db.query("UPDATE platform_model_reservations SET dispatch_state='unknown',created_at=now()-interval '3 days' WHERE id=$1",[legacy]);
 assert.equal(await recoverCreditReceipts(db),1);assert.equal(await recoverCreditReceipts(db),0);
 assert.equal((await creditBalance(db,tenant)).spent,31);assert.equal((await creditBalance(db,tenant)).reserved,300);
 await assert.rejects(dispatchCredits(db,unknown,'provider-c'),/conflict/);
 await rejectedCredits(db,unknown);await dispatchCredits(db,unknown,'provider-c');
 await receiptCredits(db,unknown,7);
 await Promise.all([settleCredits(db,unknown,7),recoverCreditReceipts(db)]);
 assert.equal((await creditBalance(db,tenant)).spent,38);assert.equal((await creditBalance(db,tenant)).reserved,200);
 await assert.rejects(settleCredits(db,waiting,-1),/invalid_credit_usage/);
 assert.deepEqual((await db.query('SELECT id FROM platform_model_reservations ORDER BY id')).map(x=>x.id),[legacy,waiting].sort());
 assert.equal((await app.inject({url:'/v1/admin/platform-model-reservations',cookies})).statusCode,403);
 assert.equal(await releaseUndispatchedCredits(db,legacy),false);
 assert.equal(await releaseUndispatchedCredits(db,waiting),true);
 assert.equal(await releaseUndispatchedCredits(db,waiting),false);
 assert.equal((await creditBalance(db,tenant)).reserved,100);
 await db.query('UPDATE users SET is_admin=true WHERE id=$1',[auth.json().user.id]);
 const audit=await app.inject({url:'/v1/admin/platform-model-reservations',cookies});assert.equal(audit.statusCode,200,audit.body);assert.equal(audit.json().items.length,1);
});
